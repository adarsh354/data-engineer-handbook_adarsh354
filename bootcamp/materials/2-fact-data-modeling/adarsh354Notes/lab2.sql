--ANALYTIC QUERY TO GENERATE DATES ACTIVE ONTO A BINARY FORM SIMILAR TO SAYING '1' FOR A ACTIVE DAY OF 30 BITS
WITH SERIES AS (
    SELECT
    GENERATE_SERIES(
        DATE('2023-01-01'),
        DATE('2023-01-31'),
        INTERVAL '1 DAY'
    ) AS DATE_SERIES
),
USERS AS (
    SELECT * FROM users_cumulated
    WHERE CURR_DATE = DATE('2023-01-31')
),
PLACEHOLDER_INTS AS(
    SELECT
    CURR_DATE - DATE(DATE_SERIES),
    CASE WHEN 
        DATES_ACTIVE @> ARRAY[DATE(DATE_SERIES)]
        THEN CAST(POW(2, 32 - (CURR_date - date(date_series))) AS BIGINT)
        else 0
    END as placeholder,
    *
FROM USERS CROSS JOIN SERIES
)
--******IMP QUERY TO GENRATE ACTIVE FLAGS THE BEST WAY
SELECT
USER_ID,
SUM(PLACEHOLDER),
CAST(CAST(SUM(PLACEHOLDER) AS BIGINT)AS BIT(32)),
BIT_COUNT(
    CAST(CAST(SUM(PLACEHOLDER) AS BIGINT)AS BIT(32))
    ) > 0  AS DIM_IS_MONTHLY_ACTIVE,
BIT_COUNT(
    cast('11111110000000000000000000000000' as BIT(32))&
    CAST(CAST(SUM(PLACEHOLDER) AS BIGINT)AS BIT(32))
) > 0 AS DIM_IS_MONTHLY_ACTIVE,
BIT_COUNT(
    cast('10000000000000000000000000000000' as BIT(32))&
    CAST(CAST(SUM(PLACEHOLDER) AS BIGINT)AS BIT(32))
) > 0 AS DIM_IS_DAILY_ACTIVE
FROM PLACEHOLDER_INTS
GROUP BY USER_ID