-- INCREMENTAL QUERY TO LOAD CUMULATIVE TABLE
WITH YESTERDAY AS (
    SELECT *
    FROM users_cumulated
    WHERE CURR_DATE = DATE('2023-01-30')
),
TODAY AS(
    SELECT 
    CAST(USER_ID AS TEXT) AS USER_ID,
    DATE(CAST(EVENT_TIME AS TIMESTAMP)) AS DATE_ACTIVE
    FROM events
    WHERE DATE(CAST(EVENT_TIME AS TIMESTAMP)) = DATE('2023-01-31')
    AND USER_ID IS NOT NULL
    GROUP BY USER_ID, DATE(CAST(EVENT_TIME AS TIMESTAMP))
)
INSERT INTO users_cumulated
SELECT 
COALESCE(YT.USER_ID, TD.USER_ID) AS USER_ID,
CASE
    WHEN TD.DATE_ACTIVE IS NULL THEN YT.DATES_ACTIVE
    ELSE ARRAY[TD.DATE_ACTIVE]||YT.DATES_ACTIVE
END AS DATES_ACTIVE,
COALESCE(TD.DATE_ACTIVE, YT.CURR_DATE + INTERVAL '1 DAY') AS CURR_DATE
FROM YESTERDAY YT 
FULL OUTER JOIN TODAY TD
ON YT.USER_ID = TD.USER_ID;

