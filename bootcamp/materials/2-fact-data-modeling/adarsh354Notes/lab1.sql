--DEDUPE BUT IN DATA SENSE OF CHOOSING THE RIGHT RECORD
WITH DEDUPE AS(
    SELECT
    G.GAME_DATE_EST,
    G.SEASON,
    G.HOME_TEAM_ID,
    G.visitor_team_id,
    GD.*,
    ROW_NUMBER() OVER(PARTITION BY GD.GAME_ID, GD.TEAM_ID, GD.player_id ORDER BY G.game_date_est) AS ROW_NUM
    FROM
    GAME_DETAILS GD JOIN GAMES G ON G.GAME_ID = GD.game_id
)
INSERT INTO fct_game_details
SELECT 
    GAME_DATE_EST,
    SEASON,
    TEAM_ID,
    PLAYER_ID,
    PLAYER_NAME,
    START_POSITION,
    TEAM_ID = HOME_TEAM_ID AS DIM_IS_PLAYING_AT_HOME,
    COALESCE(POSITION('DNP' IN COMMENT),0)>0 AS DIM_DID_NOT_PLAY,
    COALESCE(POSITION('DND' IN COMMENT),0)>0 AS DIM_DID_NOT_DRESS,
    COALESCE(POSITION('NWT' IN COMMENT),0)>0 AS DIM_DID_NOT_WITH_TEAM,
    CAST(SPLIT_PART(MIN, ':', 1)AS REAL) + CAST(SPLIT_PART(MIN, ':', 2) AS REAL)/60 AS M_MINUTES,
    FGM AS M_FGM,
    FGA AS M_FGA,
    FG3M AS M_FG3M,
    FG3A AS M_FG3A,
    FTM AS M_FTM,
    FTA AS M_FTA,
    OREB AS M_OREB,
    DREB AS M_DREB,
    REB AS M_REB,
    AST AS M_AST,
    STL AS M_STL,
    BLK AS M_BLK,
    "TO" AS M_TURNOVER,
    PF AS M_PF,
    PTS AS M_PTS,
    plus_minus AS M_PLUS_MINUS
FROM DEDUPE
WHERE ROW_NUM =1;


