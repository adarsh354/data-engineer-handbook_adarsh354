--ANALYTIC QUERY TO undestanding the blurry line between dim and fact data
SELECT
    DIM_PLAYER_NAME,
    COUNT(1) AS NUM_OF_GAMES,
    COUNT(CASE WHEN DIM_NOT_WITH_TEAM THEN 1 END) AS BAILED_NUM,
    CAST(COUNT(CASE WHEN DIM_NOT_WITH_TEAM THEN 1 END) AS REAL)/CAST(COUNT(1) AS REAL) AS BAIL_PERCENTAGE
FROM FCT_GAME_DETAILS
GROUP BY 1
ORDER BY 4 DESC;